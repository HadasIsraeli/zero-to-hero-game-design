// Logic for `npm run media:check`, kept free of I/O so it can be unit-tested.
import type { MediaCheckFile, MediaFile, YoutubeItem } from '../src/shared/lib/media-schema.ts';

export type FetchLike = (
  url: string,
) => Promise<{ ok: boolean; status: number; json: () => Promise<unknown> }>;

export type CheckRow = {
  id: string;
  title: string;
  youtubeId: string;
  ok: boolean;
  detail: string;
};

export function youtubeItems(file: MediaFile): YoutubeItem[] {
  return file.levels
    .flatMap((level) => level.media)
    .filter((item): item is YoutubeItem => item.type === 'youtube');
}

export function oembedUrl(youtubeId: string): string {
  const watch = `https://www.youtube.com/watch?v=${youtubeId}`;
  return `https://www.youtube.com/oembed?format=json&url=${encodeURIComponent(watch)}`;
}

const failureReasons: Record<number, string> = {
  400: 'bad request (malformed id?)',
  401: 'embedding disabled or video is private',
  403: 'embedding disabled or video is private',
  404: 'video not found',
};

export async function checkVideo(item: YoutubeItem, fetchImpl: FetchLike): Promise<CheckRow> {
  const base = { id: item.id, title: item.title, youtubeId: item.youtubeId };
  try {
    const response = await fetchImpl(oembedUrl(item.youtubeId));
    if (!response.ok) {
      const reason = failureReasons[response.status] ?? 'unexpected response';
      return { ...base, ok: false, detail: `HTTP ${String(response.status)}: ${reason}` };
    }
    const body = await response.json();
    const youtubeTitle =
      typeof body === 'object' && body !== null && 'title' in body && typeof body.title === 'string'
        ? body.title
        : '(no title)';
    return { ...base, ok: true, detail: `YouTube title: ${youtubeTitle}` };
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    return { ...base, ok: false, detail: `network error: ${message}` };
  }
}

export function toCheckFile(rows: CheckRow[], checkedAt: Date): MediaCheckFile {
  return {
    $comment: 'Generated by `npm run media:check`. Do not edit by hand.',
    checkedAt: checkedAt.toISOString(),
    results: Object.fromEntries(
      rows.map((row) => [row.id, { youtubeId: row.youtubeId, ok: row.ok, detail: row.detail }]),
    ),
  };
}

export function formatTable(rows: CheckRow[]): string {
  const header = ['', 'id', 'youtubeId', 'detail'];
  const body = rows.map((row) => [row.ok ? 'PASS' : 'FAIL', row.id, row.youtubeId, row.detail]);
  const widths = header.map((_, column) =>
    Math.max(...[header, ...body].map((cells) => (cells[column] ?? '').length)),
  );
  const line = (cells: string[]) =>
    cells
      .map((cell, column) => cell.padEnd(widths[column] ?? 0))
      .join('  ')
      .trimEnd();
  return [line(header), ...body.map(line)].join('\n');
}
